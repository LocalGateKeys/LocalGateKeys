#!/usr/bin/env python3
"""Generate the Kotlin casefold table from the Swift one, so both ports share a single table.

Reads the `flat` array of rows (`code point, count, folded scalars...`) from
ios/LGKCore/Sources/LGKCore/Primitives/Casefold.swift and writes
android/lgk-core/src/main/kotlin/app/localgatekeys/core/primitives/CasefoldTable.kt.

Do not regenerate from Python's unicodedata: the Swift table pins Unicode 15.0.0 and a newer
Python (3.14) carries a newer Unicode.

Usage: python scripts/make_casefold_kotlin.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SWIFT = ROOT / "ios/LGKCore/Sources/LGKCore/Primitives/Casefold.swift"
OUT = ROOT / "android/lgk-core/src/main/kotlin/app/localgatekeys/core/primitives/CasefoldTable.kt"
CHUNK_CHARS = 12000  # a string constant is limited to 65535 UTF-8 bytes; stay far below it


def read_flat(text: str) -> list[int]:
    m = re.search(r"static let flat: \[UInt32\] = \[(.*?)\n    \]", text, re.S)
    if not m:
        sys.exit("flat table not found in " + str(SWIFT))
    return [int(t, 16) for t in re.findall(r"0x([0-9A-Fa-f]+)", m.group(1))]


def validate(flat: list[int]) -> int:
    i = rows = 0
    while i < len(flat):
        n = flat[i + 1]
        if n < 1 or i + 2 + n > len(flat):
            sys.exit(f"malformed row at {i}")
        i += 2 + n
        rows += 1
    return rows


def main() -> None:
    text = SWIFT.read_text(encoding="utf-8")
    version = re.search(r"Unicode (\d+\.\d+\.\d+)", text).group(1)
    if version != "15.0.0":
        sys.exit(f"unexpected Unicode version {version}")
    flat = read_flat(text)
    rows = validate(flat)
    tokens = [format(v, "X") for v in flat]
    chunks: list[str] = []
    cur: list[str] = []
    size = 0
    for t in tokens:
        if size + len(t) + 1 > CHUNK_CHARS:
            chunks.append(",".join(cur))
            cur, size = [], 0
        cur.append(t)
        size += len(t) + 1
    if cur:
        chunks.append(",".join(cur))

    lines = [
        "// GENERATED by scripts/make_casefold_kotlin.py from",
        "// ios/LGKCore/Sources/LGKCore/Primitives/Casefold.swift (the `flat` table). Do not edit.",
        f"// Unicode {version}; {rows} code points.",
        "package app.localgatekeys.core.primitives",
        "",
        "/**",
        " * Rows of `code point, count, folded scalars...` as comma-separated hex, split into chunks so no",
        " * string constant or method nears the JVM limits.",
        " */",
        "internal object CasefoldTable {",
        f"    const val UNICODE_VERSION = \"{version}\"",
        "",
        "    val flat: IntArray by lazy {",
        "        val out = IntArray(TOTAL)",
        "        var n = 0",
        "        for (chunk in chunks()) {",
        "            for (tok in chunk.split(',')) out[n++] = tok.toInt(16)",
        "        }",
        "        check(n == TOTAL) { \"casefold table corrupt\" }",
        "        out",
        "    }",
        "",
        f"    private const val TOTAL = {len(flat)}",
        "",
        "    private fun chunks(): List<String> = listOf(",
    ]
    lines += [f"        chunk{i}()," for i in range(len(chunks))]
    lines.append("    )")
    for i, c in enumerate(chunks):
        lines += ["", f"    private fun chunk{i}(): String ="]
        # one literal per chunk, wrapped over several source lines by concatenation of short pieces
        parts = [c[j : j + 100] for j in range(0, len(c), 100)]
        for k, p in enumerate(parts):
            lines.append(f"        \"{p}\"" + (" +" if k < len(parts) - 1 else ""))
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({rows} rows, {len(chunks)} chunks)")


if __name__ == "__main__":
    main()
