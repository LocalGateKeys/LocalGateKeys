#!/usr/bin/env python3
"""Convert the bundled site logos for the Android app, deterministically.

Reads the iPhone image sets (ios/App/SiteLogos.xcassets/logo-<slug>.imageset/logo-<slug>.svg, one 24x24 path each)
and the desktop table src/localvault/assets/site_logos.json, and writes

  android/app/src/main/res/drawable/logo_<slug>.xml            one white vector drawable per logo (tinted when drawn)
  android/app/src/main/kotlin/app/localgatekeys/android/vault/SiteLogoImages.kt   slug -> R.drawable id
  android/app/src/main/assets/site_logos.json                  byte copy of the desktop table

Every logo of the table must have an image set and the other way round, or the script stops. Run it again after the
desktop table or the iPhone images change; the output has no timestamps, so a rerun on unchanged input changes nothing.

Usage: python scripts/make_android_logos.py
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "src/localvault/assets/site_logos.json"
IMAGES = ROOT / "ios/App/SiteLogos.xcassets"
APP = ROOT / "android/app/src/main"
DRAWABLES = APP / "res/drawable"
ASSET = APP / "assets/site_logos.json"
KOTLIN = APP / "kotlin/app/localgatekeys/android/vault/SiteLogoImages.kt"

SLUG = re.compile(r"^[a-z0-9]+$")


def svg_path(slug: str) -> str:
    svg = (IMAGES / f"logo-{slug}.imageset" / f"logo-{slug}.svg").read_text(encoding="utf-8")
    if svg.count("<path") != 1 or re.search(r"<g[ >]|transform|clip|fill-rule", svg) or 'viewBox="0 0 24 24"' not in svg:
        sys.exit(f"logo-{slug}.svg is not a single plain 24x24 path")
    m = re.search(r'<path d="([^"]+)"', svg)
    if not m:
        sys.exit(f"logo-{slug}.svg has no path data")
    return m.group(1)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))  # LF, no BOM


def main() -> None:
    table = json.loads(TABLE.read_text(encoding="utf-8"))
    slugs = sorted(table["logos"])
    on_disk = sorted(p.name[len("logo-"):-len(".imageset")] for p in IMAGES.glob("logo-*.imageset"))
    if slugs != on_disk:
        sys.exit(f"table and image sets differ: {sorted(set(slugs) ^ set(on_disk))}")
    for slug in slugs:
        if not SLUG.match(slug):
            sys.exit(f"slug {slug!r} cannot be an Android resource name")

    if DRAWABLES.exists():
        for old in DRAWABLES.glob("logo_*.xml"):
            old.unlink()
    for slug in slugs:
        write(DRAWABLES / f"logo_{slug}.xml",
              '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
              '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
              f'    <path android:fillColor="#FFFFFFFF" android:pathData="{svg_path(slug)}" />\n'
              '</vector>\n')

    rows = "".join(f'        "{s}" to R.drawable.logo_{s},\n' for s in slugs)
    write(KOTLIN,
          "// Generated by scripts/make_android_logos.py. Do not edit by hand.\n"
          "package app.localgatekeys.android.vault\n\n"
          "import app.localgatekeys.android.R\n\n"
          "/** Bundled site logo drawables by slug (white glyphs, tinted when drawn). */\n"
          "internal object SiteLogoImages {\n"
          "    val ids: Map<String, Int> = mapOf(\n" + rows + "    )\n}\n")

    ASSET.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(TABLE, ASSET)
    print(f"{len(slugs)} logos")


if __name__ == "__main__":
    main()
