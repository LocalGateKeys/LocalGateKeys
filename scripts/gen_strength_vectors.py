def common_samples() -> list[str]:
    return [p for k, p in enumerate(COMMON_PASSWORDS) if k % 6 == 0]


def word_phrases() -> list[str]:
    rng = random.Random(20261027)
    words = list(load_wordlist())
    out = [words[k] for k in range(0, len(words), 250)]
    for _ in range(40):
        sep = rng.choice(["-", " ", "", "_", "."])
        phrase = sep.join(rng.choice(words) for _ in range(rng.randint(1, 5)))
        if rng.random() < 0.3:
            phrase = phrase.title()
        if rng.random() < 0.3:
            phrase += str(rng.randint(0, 99))
        out.append(phrase)
    return out


def swift_lists() -> str:
    words = sorted(password_tools._word_set())  # noqa: SLF001
    def lit(values: list[str]) -> str:
        return ",\n".join("        " + json.dumps(v, ensure_ascii=False) for v in values)
    return (
        "// Generated by scripts/gen_strength_vectors.py from src/localvault/password_tools.py. Do not edit.\n\n"
        "enum StrengthLists {\n"
        "    /// Desktop `COMMON_PASSWORDS`, most common first (rank = first lower-cased occurrence).\n"
        f"    static let common: [String] = [\n{lit(list(COMMON_PASSWORDS))},\n    ]\n\n"
        "    /// Desktop `len(load_wordlist())`: the guess rank of any dictionary word.\n"
        f"    static let wordRank = {len(load_wordlist())}\n\n"
        "    /// Desktop `_word_set()`: the packaged word list plus the built-in fallback list (sorted).\n"
        f"    static let words: [String] = [\n{lit(words)},\n    ]\n"
        "}\n"
    )


def main() -> int:
    seen: set[str] = set()
    vectors: list[dict[str, object]] = []
    for password in list(KNOWN) + EXTRA + HAND_PICKED + common_samples() + word_phrases() + random_passwords(240):
        if password in seen:
            continue
        seen.add(password)
        try:
            estimate = estimate_strength(password)
        except (OverflowError, ValueError):
            continue
        vectors.append({"password": password, "score": estimate.score, "guesses_log10": round(estimate.guesses_log10, 6)})
    for password, score in KNOWN.items():
        got = next(v["score"] for v in vectors if v["password"] == password)
        if got != score:
            raise SystemExit(f"desktop score for {password!r} is {got}, expected {score}")
    out = ROOT / "tests" / "vectors" / "strength" / "vectors.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(vectors, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    lists = ROOT / "ios" / "LGKCore" / "Sources" / "LGKCore" / "Strength" / "StrengthLists.swift"
    lists.write_text(swift_lists(), encoding="utf-8", newline="\n")
    print(f"{len(vectors)} vectors -> {out}\nlists -> {lists}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
