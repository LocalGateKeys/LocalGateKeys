"""Pin the Mac/iPhone strength estimator (LGKCore ``PasswordStrength``) to the desktop.

Writes two files from ``localvault.password_tools``:

* ``tests/vectors/strength/vectors.json``: ``[{password, score, guesses_log10}]`` from
  ``estimate_strength`` for a fixed password list (hand-picked cases for every matcher, samples of the
  common list and the word list, l33t, reversed, dates, keyboard runs, repeats, sequences, Unicode,
  long inputs, plus a seeded random set).
* ``ios/LGKCore/Sources/LGKCore/Strength/StrengthLists.swift``: the common-password list in its exact
  order and the dictionary word set (``_word_set()``) with its rank (``len(load_wordlist())``).

Usage::

    python scripts/gen_strength_vectors.py

Read-only apart from those two files. Passwords for which the desktop itself raises (a float overflow
on inputs of several hundred characters) are left out.
"""

