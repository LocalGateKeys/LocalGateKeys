"""Writes tests/vectors/vault_sort/cases.json: the vault list sort rule shared by every app.

Rule (version 1):
* Options: ``title_asc``, ``title_desc``, ``modified_desc`` (``updated_at``), ``created_desc`` (``created_at``).
* Title key: NFKD, drop combining marks (general category Mn), then lowercase per Unicode simple case
  mapping (Python ``str.lower``), compared by Unicode code points. A missing title is "".
* Missing or non-integer timestamps count as 0.
* Ties: title key ascending, then ``id`` ascending (code points), for every option (title_desc reverses
  only the title comparison, its ties still go by id ascending).
* ``favorites_first``: favorites before the rest, each group sorted as above.
* With a search query the list keeps relevance order; sorting applies to the plain list only.
"""
from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "tests" / "vectors" / "vault_sort" / "cases.json"

ITEMS = [
    {"id": "i1", "title": "github", "favorite": False, "created_at": 100, "updated_at": 900},
    {"id": "i2", "title": "Amazon", "favorite": True, "created_at": 300, "updated_at": 300},
    {"id": "i3", "title": "Éclair bakery", "favorite": False, "created_at": 200, "updated_at": 950},
    {"id": "i4", "title": "bank", "favorite": True, "created_at": 300, "updated_at": 100},
    {"id": "i5", "title": "GitHub", "favorite": False, "created_at": 50, "updated_at": 900},
    {"id": "i6", "title": "", "favorite": False, "created_at": 0, "updated_at": 0},
    {"id": "i7", "title": "Ｚoom", "favorite": False, "created_at": 400, "updated_at": 400},
    {"id": "i0", "title": "eclair", "favorite": False, "updated_at": 10},
]


def title_key(item: dict) -> str:
    text = unicodedata.normalize("NFKD", item.get("title") or "")
    return "".join(c for c in text if unicodedata.category(c) != "Mn").lower()


def stamp(item: dict, key: str) -> int:
    v = item.get(key)
    return v if isinstance(v, int) and not isinstance(v, bool) else 0


def order(items: list[dict], option: str, favorites_first: bool) -> list[str]:
    def base(it: dict):
        t = title_key(it)
        if option == "title_asc":
            return (t, it["id"])
        if option == "title_desc":
            return ([-ord(c) for c in t] + [1], it["id"])  # reversed code points; shorter prefix sorts after
        field = "updated_at" if option == "modified_desc" else "created_at"
        return (-stamp(it, field), t, it["id"])

    ranked = sorted(items, key=base)
    if favorites_first:
        ranked = [i for i in ranked if i["favorite"]] + [i for i in ranked if not i["favorite"]]
    return [i["id"] for i in ranked]


def main() -> int:
    cases = [{"option": o, "favorites_first": f, "expected": order(ITEMS, o, f)}
             for o in ("title_asc", "title_desc", "modified_desc", "created_desc") for f in (False, True)]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"_comment": "Generated by scripts/make_sort_vectors.py; see its docstring for the rule.",
                               "items": ITEMS, "cases": cases}, ensure_ascii=False, indent=2) + "\n",
                   encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
