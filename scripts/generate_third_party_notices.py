"""Write THIRD-PARTY-NOTICES.txt from the licences of the locked runtime dependencies.

The installer and the Store package ship this file next to LocalGateKeys.exe
(audit 2026-10-24 I-23). Every package pinned in requirements.lock.txt that is
installed for this platform contributes its licence files from its
``*.dist-info`` (LICENSE, COPYING, NOTICE, ...); the bundled CPython runtime
contributes its LICENSE.txt, and the PyInstaller bootloader its licence
exception. The installed versions must match the lock, so run it from the
release venv:

    .venv\\Scripts\\python.exe scripts\\generate_third_party_notices.py          # rewrite
    .venv\\Scripts\\python.exe scripts\\generate_third_party_notices.py --check  # exit 1 if stale

Output is deterministic (sorted, LF line endings) so a stale copy shows up as a diff.
"""

from __future__ import annotations

import argparse
import importlib.metadata as metadata
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements.lock.txt"
OUT = ROOT / "THIRD-PARTY-NOTICES.txt"
LICENCE_FILE = re.compile(r"(^|/)(LICEN[CS]E|COPYING|NOTICE|AUTHORS)[^/]*$", re.IGNORECASE)
PIN = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s;\\]+)\s*(?:;\s*([^\\]+?))?\s*\\?\s*$")
RULE = "=" * 78

# Licence expressions for packages whose metadata has none or only prose.
KNOWN_LICENCES = {
    "clr-loader": "MIT",
    "segno": "BSD-3-Clause",
    "opencv-contrib-python": "Apache-2.0",
    "pywebview": "BSD-3-Clause",
    "pywinauto": "BSD-3-Clause",
    "pywin32": "PSF-2.0",
    "pystray": "LGPL-3.0-only",
    "proxy-tools": "MIT",
}

NOTES = {
    "pystray": (
        "pystray is licensed under the GNU Lesser General Public License v3.0\n"
        "(text below, with the GPL v3.0 it refers to). LocalGateKeys uses it\n"
        "unmodified. It is shipped as plain Python source files in\n"
        "_internal\\pystray\\ next to LocalGateKeys.exe (not compiled into the\n"
        "executable), so you can replace them with your own modified or newer\n"
        "version of pystray and LocalGateKeys will load it. Source code of the\n"
        "version shipped: https://pypi.org/project/pystray/ or\n"
        "https://github.com/moses-palmer/pystray (tag v{version}); we will also\n"
        "send it on request to the contact address on localgatekeys.app."
    ),
    "opencv-contrib-python": (
        "OpenCV is licensed under the Apache License 2.0. The wheel bundles\n"
        "further third-party components; their notices (LICENSE-3RD-PARTY.txt)\n"
        "follow the Apache licence text."
    ),
}


def locked_packages(lock: Path) -> list[tuple[str, str]]:
    packages = []
    for line in lock.read_text(encoding="utf-8").splitlines():
        match = PIN.match(line)
        if match is None:
            continue
        name, version, marker = match.groups()
        # The lock's only markers are platform_system == "Windows"; the notices
        # describe the Windows build, so they are always included.
        if marker and 'platform_system == "Windows"' not in marker:
            raise SystemExit(f"unexpected environment marker in the lock: {name}; {marker}")
        packages.append((name, version))
    return sorted(packages, key=lambda p: p[0].lower())


def licence_texts(dist: metadata.Distribution) -> list[tuple[str, str]]:
    found = []
    for file in dist.files or []:
        path = str(file).replace("\\", "/")
        if ".dist-info/" not in path or not LICENCE_FILE.search(path):
            continue
        text = Path(dist.locate_file(file)).read_text(encoding="utf-8", errors="replace")
        found.append((path.split(".dist-info/", 1)[1], text))
    return sorted(found)


def licence_expression(name: str, dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression.strip()
    if name.lower() in KNOWN_LICENCES:
        return KNOWN_LICENCES[name.lower()]
    text = (meta.get("License") or "").strip().splitlines()
    return text[0][:60] if text else "see licence text"


def section(title: str, body: str) -> str:
    return f"{RULE}\n{title}\n{RULE}\n\n{body.strip()}\n\n"


def normalise(text: str) -> str:
    return "\n".join(line.rstrip() for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n"))


def build(lock: Path) -> str:
    packages = locked_packages(lock)
    parts = [
        "LocalGateKeys third-party notices\n\n"
        "LocalGateKeys for Windows includes the software listed below. Each is\n"
        "used under the licence shown, whose full text follows in this file.\n"
        "Generated by scripts/generate_third_party_notices.py from\n"
        "requirements.lock.txt; do not edit by hand.\n\n"
    ]
    summary = ["Python runtime (CPython)  PSF-2.0 (and bundled components)", "PyInstaller bootloader  GPL-2.0-or-later WITH Bootloader exception"]
    bodies = []
    for name, version in packages:
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError as exc:
            raise SystemExit(f"{name}=={version} is locked but not installed; run from the release venv") from exc
        if dist.version != version:
            raise SystemExit(f"{name}: installed {dist.version}, lock pins {version}; install the lock first")
        expression = licence_expression(name, dist)
        summary.append(f"{name} {version}  {expression}")
        texts = licence_texts(dist)
        body = []
        if name.lower() in NOTES:
            body.append(NOTES[name.lower()].format(version=version))
        if not texts:
            body.append(f"Licence: {expression}. The package ships no licence file; see {dist.metadata.get('Home-page') or 'https://pypi.org/project/' + name}.")
        for filename, text in texts:
            body.append(f"--- {filename} ---\n\n{normalise(text).strip()}")
        bodies.append(section(f"{name} {version} ({expression})", "\n\n".join(body)))

    python_licence = Path(sys.base_prefix) / "LICENSE.txt"
    runtime = (
        normalise(python_licence.read_text(encoding="utf-8", errors="replace"))
        if python_licence.is_file()
        else "Python Software Foundation License Version 2: https://docs.python.org/3/license.html"
    )
    runtime_title = "Python {0}.{1} runtime".format(*sys.version_info[:2])
    bodies.insert(0, section(runtime_title + " (PSF-2.0; includes OpenSSL, Apache-2.0, and others)", runtime))
    bodies.insert(1, section(
        "PyInstaller bootloader (GPL-2.0-or-later WITH Bootloader exception)",
        "LocalGateKeys.exe and LocalGateKeysNativeHost.exe start through the\n"
        "PyInstaller bootloader. Its licence allows distributing it with programs\n"
        "under any licence (the bootloader exception):\n"
        "https://github.com/pyinstaller/pyinstaller/blob/develop/COPYING.txt",
    ))
    parts.append("Summary\n\n" + "\n".join(f"  {line}" for line in summary) + "\n\n")
    parts.extend(bodies)
    return "".join(parts).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--lock", type=Path, default=LOCK)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is missing or stale")
    args = parser.parse_args(argv)
    text = build(args.lock)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else ""
        if current != text:
            print(f"{args.out} is stale: run scripts/generate_third_party_notices.py", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date")
        return 0
    args.out.write_bytes(text.encode("utf-8"))
    print(f"wrote {args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
