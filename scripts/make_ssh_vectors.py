"""Generate the SSH key vectors in ``tests/vectors/ssh`` (test-only, published).

Every key is freshly generated by this script and is public test material; none
protects anything.  Passphrase-protected keys use the passphrase ``vector-pass``.
Mac (Task 9) mirrors these files, so regenerate only on purpose.  ``bcrypt_pbkdf.json`` (OpenSSH's key
derivation for encrypted keys, from Python ``bcrypt.kdf``) is deterministic; ``--bcrypt-only`` rewrites just that
file and leaves the keys alone.

    python scripts/make_ssh_vectors.py [--bcrypt-only] [OUT_DIR]     # default: tests/vectors/ssh
"""
from __future__ import annotations

import base64
import binascii
import hashlib
import json
import struct
import sys
from pathlib import Path

import bcrypt
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, rsa

PASSPHRASE = "vector-pass"  # noqa: S105 (test-only, published)
SIGN_DATA = b"localgatekeys ssh vector data"


def _string(data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + data


def _mpint(value: int) -> bytes:
    raw = value.to_bytes((value.bit_length() + 7) // 8, "big")
    return _string((b"\x00" + raw) if raw[0] & 0x80 else raw)


def _public_blob(key_type: str, private) -> bytes:
    pub = private.public_key()
    if key_type == "ssh-ed25519":
        return _string(b"ssh-ed25519") + _string(
            pub.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        )
    if key_type == "ssh-rsa":
        n = pub.public_numbers()
        return _string(b"ssh-rsa") + _mpint(n.e) + _mpint(n.n)
    point = pub.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
    return _string(key_type.encode()) + _string(key_type.rsplit("-", 1)[1].encode()) + _string(point)


def _fingerprint(blob: bytes) -> str:
    return "SHA256:" + base64.b64encode(hashlib.sha256(blob).digest()).decode().rstrip("=")


def _sk_key() -> str:
    """A syntactically valid unencrypted OpenSSH container holding an sk-ed25519 key (no real key)."""
    kt = b"sk-ssh-ed25519@openssh.com"
    pub = _string(kt) + _string(b"\x01" * 32) + _string(b"ssh:")
    inner = struct.pack(">II", 0x1234, 0x1234) + pub + _string(b"\x02" * 32) + _string(b"")
    inner += bytes(range(1, 1 + (-len(inner)) % 8))
    raw = b"openssh-key-v1\x00" + _string(b"none") + _string(b"none") + _string(b"") + struct.pack(">I", 1)
    raw += _string(pub) + _string(inner)
    b64 = base64.b64encode(raw).decode()
    lines = [b64[i:i + 70] for i in range(0, len(b64), 70)]
    return "-----BEGIN OPENSSH PRIVATE KEY-----\n" + "\n".join(lines) + "\n-----END OPENSSH PRIVATE KEY-----\n"


# (name, password, salt, rounds, length): OpenSSH's default (16 rounds, 48 bytes = AES-256 key + IV), short and
# long outputs (the stride spreads bytes over several blocks), one round, a non-ASCII password.
_BCRYPT_CASES = [
    ("openssh_default", PASSPHRASE, bytes(range(16)), 16, 48),
    ("short_salt", "password", b"salt", 4, 32),
    ("one_round_one_byte", "x", b"y" * 32, 1, 1),
    ("unicode_long", "pässwörd ✓", bytes(range(100, 132)), 8, 80),
    ("odd_length", "p", b"s", 2, 33),
    ("aes128_key", "correct horse battery staple", bytes(range(200, 216)), 16, 32),
]


def write_bcrypt_vectors(out: Path) -> None:
    cases = []
    for name, password, salt, rounds, length in _BCRYPT_CASES:
        key = bcrypt.kdf(password.encode("utf-8"), salt, length, rounds, ignore_few_rounds=True)
        cases.append({"name": name, "password": password, "salt_hex": binascii.hexlify(salt).decode(),
                      "rounds": rounds, "length": length, "key_hex": binascii.hexlify(key).decode()})
    (out / "bcrypt_pbkdf.json").write_text(json.dumps({"cases": cases}, indent=2, ensure_ascii=False) + "\n",
                                           encoding="utf-8", newline="\n")


def main(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    keys = {
        "ed25519": ("ssh-ed25519", ed25519.Ed25519PrivateKey.generate()),
        "ecdsa256": ("ecdsa-sha2-nistp256", ec.generate_private_key(ec.SECP256R1())),
        "ecdsa384": ("ecdsa-sha2-nistp384", ec.generate_private_key(ec.SECP384R1())),
        "rsa3072": ("ssh-rsa", rsa.generate_private_key(65537, 3072)),
    }
    expected: dict = {"passphrase": PASSPHRASE, "sign_data_b64": base64.b64encode(SIGN_DATA).decode(), "keys": {}}
    for name, (key_type, private) in keys.items():
        for suffix, enc in (("", serialization.NoEncryption()),
                            ("_enc", serialization.BestAvailableEncryption(PASSPHRASE.encode()))):
            pem = private.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.OpenSSH, enc)
            (out / f"{name}{suffix}.key").write_bytes(pem)
        blob = _public_blob(key_type, private)
        line = f"{key_type} {base64.b64encode(blob).decode()} test-only {name}"
        (out / f"{name}.pub").write_text(line + "\n", encoding="ascii", newline="\n")
        entry = {"key_type": key_type, "public_line": line, "fingerprint": _fingerprint(blob)}
        if name == "ed25519":
            sig = private.sign(SIGN_DATA)
            entry["signature_blob_b64"] = base64.b64encode(_string(b"ssh-ed25519") + _string(sig)).decode()
        expected["keys"][name] = entry
    (out / "putty.ppk").write_text(
        "PuTTY-User-Key-File-3: ssh-ed25519\nEncryption: none\nComment: test-only, published\n"
        "Public-Lines: 2\nAAAA\nBBBB\nPrivate-Lines: 1\nCCCC\nPrivate-MAC: 00\n", newline="\n")
    (out / "sk_ed25519.key").write_text(_sk_key(), newline="\n")
    (out / "README.md").write_text(
        "Test-only, published SSH keys made by `scripts/make_ssh_vectors.py`. They protect nothing.\n"
        f"Passphrase of the `*_enc.key` files: `{PASSPHRASE}`.\n"
        "`bcrypt_pbkdf.json`: OpenSSH bcrypt_pbkdf outputs from Python `bcrypt.kdf` (`--bcrypt-only` rewrites it).\n",
        newline="\n")
    (out / "expected.json").write_text(json.dumps(expected, indent=2, sort_keys=True) + "\n", newline="\n")
    write_bcrypt_vectors(out)


if __name__ == "__main__":
    args = sys.argv[1:]
    bcrypt_only = "--bcrypt-only" in args
    args = [a for a in args if a != "--bcrypt-only"]
    target = Path(args[0]) if args else Path(__file__).resolve().parents[1] / "tests" / "vectors" / "ssh"
    if bcrypt_only:
        target.mkdir(parents=True, exist_ok=True)
        write_bcrypt_vectors(target)
    else:
        main(target)
