"""Phone backup format 2 vectors (tests/vectors/backup/format2): document files in the payload.

Regenerated byte for byte by ``test_backup_vectors.test_generator_reproduces_committed_files_byte_for_byte``.
"""

from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path

import pytest

from localvault.phone_backup import PhoneBackupError, inspect_phone_backup, read_phone_backup, write_phone_backup
from localvault.sync.attachment_sync import AttachmentRef, open_blob

ROOT = Path(__file__).resolve().parents[1]
VEC = ROOT / "tests" / "vectors" / "backup"
V2 = VEC / "format2"
EXPECTED_V1 = json.loads((VEC / "expected.json").read_text(encoding="utf-8"))
EXPECTED = json.loads((V2 / "expected.json").read_text(encoding="utf-8"))
ATTACHMENTS = json.loads((ROOT / "tests" / "vectors" / "sync" / "attachments" / "vectors.json").read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def backup():
    return read_phone_backup((V2 / "backup.lgkm").read_bytes(), EXPECTED["password"])


def test_header_is_version_2_and_aad_matches():
    data = (V2 / "backup.lgkm").read_bytes()
    assert inspect_phone_backup(data).version == 2
    assert json.loads(data)["header"] == EXPECTED["header"]
    assert len(data) == EXPECTED["file_size"] and hashlib.sha256(data).hexdigest() == EXPECTED["file_sha256"]


def test_states_and_file_open(backup):
    got = [{"deleted": s.deleted, "deleted_at": s.deleted_at, "id": s.item_id, "item": s.item, "vv": dict(s.vv)}
           for s in backup.states]
    assert got == EXPECTED["states"]
    assert [s for s in got if s["id"] != EXPECTED["document_id"]] == EXPECTED_V1["states"]
    (entry,) = EXPECTED["files"]
    assert list(backup.files) == [entry["blob"]]
    doc = next(s for s in backup.states if s.item_id == EXPECTED["document_id"])
    ref = AttachmentRef.from_value(doc.item["attachment"])
    small = next(b for b in ATTACHMENTS["blobs"] if b["name"] == "small")
    assert open_blob(backup.files[ref.blob], ref) == base64.b64decode(small["plaintext"])


def test_writing_again_gives_the_same_bytes(backup):
    again = write_phone_backup(
        backup.states, password=EXPECTED["password"], device_id=backup.device_id, platform=backup.header.platform,
        app_version=backup.app_version, created_at=backup.header.created_at, pro_hint=backup.pro_hint,
        files=backup.files, _salt=backup.header.salt, _nonce=backup.header.nonce)
    assert again == (V2 / "backup.lgkm").read_bytes()


def test_rejected_listing_is_complete():
    assert sorted(p.name for p in (V2 / "rejected").glob("*.lgkm")) == sorted(EXPECTED["rejected"])
    assert "version_3.lgkm" in EXPECTED_V1["rejected"] and "version_2.lgkm" not in EXPECTED_V1["rejected"]


@pytest.mark.parametrize("name", sorted(EXPECTED["rejected"]))
def test_rejected_vectors_give_their_reason(name):
    entry = EXPECTED["rejected"][name]
    with pytest.raises(PhoneBackupError) as info:
        read_phone_backup((V2 / "rejected" / name).read_bytes(), entry["password"])
    assert info.value.reason == entry["reason"]


def test_vector_restores_with_its_file(tmp_path, backup):
    from test_sync_vault_bridge import FakeLease, _vault

    from localvault.attachments import AttachmentStore
    from localvault.sync.phone_restore import plan_restore, restore

    desk = _vault(tmp_path, "desk")
    desk.item_limit = None
    desk.pro_features = None
    lease = FakeLease()
    t = backup.header.created_at + 2000
    plan = plan_restore(desk, lease, backup, now=t)
    assert len(plan.files) == 1 and plan.files_missing == 0
    report = restore(desk, lease, plan, now=t)
    assert report.files == 1 and "attachment-refused" not in report.issues
    doc = next(i for i in desk._payload["items"] if i["id"] == EXPECTED["document_id"])
    small = next(b for b in ATTACHMENTS["blobs"] if b["name"] == "small")
    assert AttachmentStore(desk).read_bytes(doc["payload"]["attachment_id"]) == base64.b64decode(small["plaintext"])
