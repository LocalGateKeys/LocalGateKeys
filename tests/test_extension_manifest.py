import base64
import hashlib
import importlib.util
import json
from pathlib import Path

from PIL import Image, ImageChops

from localvault.config import EXTENSION_ID


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = json.loads((ROOT / "browser-extension" / "manifest.json").read_text(encoding="utf-8"))
_BRAND_SPEC = importlib.util.spec_from_file_location("generate_brand_icons", ROOT / "scripts" / "generate_brand_icons.py")
brand_icons = importlib.util.module_from_spec(_BRAND_SPEC)
_BRAND_SPEC.loader.exec_module(brand_icons)


def extension_id_from_public_key(public_key_b64: str) -> str:
    digest_prefix = hashlib.sha256(base64.b64decode(public_key_b64)).hexdigest()[:32]
    return "".join(chr(ord("a") + int(nibble, 16)) for nibble in digest_prefix)


def test_extension_uses_stable_expected_id() -> None:
    assert extension_id_from_public_key(MANIFEST["key"]) == EXTENSION_ID


def test_extension_has_user_requested_all_sites_access() -> None:
    # Static host access is required: the save-prompt flow must observe a
    # submit before any click on the extension (see SECURITY.md, Browser
    # boundary). activeTab covers the popup's manual fill on Firefox, where
    # MV3 host permissions are optional until the user grants them.
    assert set(MANIFEST["host_permissions"]) == {"http://*/*", "https://*/*"}
    assert "optional_host_permissions" not in MANIFEST
    assert set(MANIFEST["permissions"]) == {"nativeMessaging", "scripting", "storage", "webNavigation", "favicon", "activeTab"}


def test_content_script_runs_in_all_same_origin_frames_in_isolated_world() -> None:
    # Passkey scripts (webauthn-*) are checked in tests/extension/firefox-manifest.test.cjs
    # and security-audit.test.cjs; this test covers the fill content script.
    scripts = [cs for cs in MANIFEST["content_scripts"] if not any(f.startswith("webauthn-") for f in cs["js"])]
    assert len(scripts) == 1
    script = scripts[0]
    assert set(script["matches"]) == {"http://*/*", "https://*/*"}
    # Injected into every frame; content.js and background.js both reject
    # frames with a cross-origin ancestor, so only same-origin iframes act.
    assert script["all_frames"] is True
    assert script["world"] == "ISOLATED"
    assert script["js"] == ["api.js", "heuristics.js", "login-safety.js", "content.js"]


def test_extension_pages_have_a_strict_csp_and_a_stable_firefox_id() -> None:
    assert MANIFEST["content_security_policy"]["extension_pages"] == "script-src 'self'; object-src 'self'"
    gecko = MANIFEST["browser_specific_settings"]["gecko"]
    assert gecko["id"] == "localgatekeys@localgatekeys.app"
    assert gecko["strict_min_version"]
    # Chrome 106+ rejects background.scripts next to service_worker; the
    # Firefox variant is generated by browser-extension/build-firefox-manifest.cjs.
    assert MANIFEST["background"] == {"service_worker": "background.js"}
    assert not (ROOT / "browser-extension" / "auto-mode.js").exists()


def test_no_extension_resource_is_web_accessible() -> None:
    # The in-page icons are inline SVG inside closed shadow roots, so pages
    # cannot fingerprint the extension by probing a static extension URL.
    assert "web_accessible_resources" not in MANIFEST
    content = (ROOT / "browser-extension" / "content.js").read_text(encoding="utf-8")
    assert "getURL" not in content
    assert "icons/icon" not in content
    assert "function logoGlyph()" in content


def test_field_fill_density_assets_are_packaged_and_shared_with_desktop() -> None:
    paths = [
        *(ROOT / "browser-extension" / "icons" / f"icon{size}.png" for size in (16, 32, 48, 128)),
        *(ROOT / "assets" / "icons" / f"field_fill_{size}.png"
          for size in (24, 30, 32, 36, 42, 48, 64, 96, 128)),
        *(ROOT / "assets" / "icons" / f"app_{size}.png"
          for size in (16, 20, 24, 32, 40, 48, 64, 96, 128, 256)),
    ]
    for path in paths:
        size = Image.open(path).size[0]
        with Image.open(path).convert("RGBA") as actual:
            assert ImageChops.difference(actual, brand_icons.icon_image(size)).getbbox() is None, path


