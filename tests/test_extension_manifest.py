def test_browser_extension_supports_multi_account_selection_and_update_detection() -> None:
    root = Path(__file__).resolve().parents[1]
    content = (root / "browser-extension" / "content.js").read_text(encoding="utf-8")
    background = (root / "browser-extension" / "background.js").read_text(encoding="utf-8")
    # Update detection moved to the desktop app (audit M-3): the page shows one neutral prompt.
    assert 'status==="exists"' in content and 'Update saved password?' not in content
    assert 'pending_token' in content and 'loginOutcome' in content and 'Did you just sign in?' in content
    assert 'check_pending_save' in content and 'document.addEventListener("focusout"' not in content
    assert 'onDOMContentLoaded?.addListener(nudgePendingSave)' in background
    assert 'onCompleted?.addListener(nudgePendingSave)' in background
    assert 'onHistoryStateUpdated?.addListener(nudgePendingSave)' in background
    assert "showAccountPicker" in content
    assert "request.entry_id" in background
    from localvault.version import APP_VERSION
    assert MANIFEST["version"] == APP_VERSION
    assert "usernameOnly" in content
    assert 'autocomplete="new-password"' in content
    assert MANIFEST["content_scripts"][0]["js"] == ["api.js", "heuristics.js", "login-safety.js", "content.js"]
    assert "documentId" in background
    assert "parentFrameId" in background  # same-origin ancestry check for iframes
    assert "automatic_save_blocked_origins" in content
    assert "recentFilledCredential" in content
    assert "clear_pending_browser" in content and "clear_pending_browser" in background
    assert "Turn off save prompts on this site" in (root / "browser-extension" / "popup.js").read_text(encoding="utf-8")
    # Login, 2FA and identity icons share the inline vault-dial logo.
    assert content.count("logoGlyph()") == 4


def test_browser_extension_uses_broker_gesture_nonces_not_ping_lease_fields() -> None:
    root = Path(__file__).resolve().parents[1]
    content = (root / "browser-extension" / "content.js").read_text(encoding="utf-8")
    background = (root / "browser-extension" / "background.js").read_text(encoding="utf-8")
    popup = (root / "browser-extension" / "popup.js").read_text(encoding="utf-8")
    # Nonce minted by begin_* / begin_gesture_browser, forwarded as gesture_nonce.
    assert '"begin_gesture_browser"' in content and '"begin_gesture_browser"' in background
    assert "gesture_nonce" in content and "payload.gesture_nonce=request.gesture_nonce" in background
    assert "/^[0-9a-f]{32}$/" in background
    assert "GESTURE_NONCE_TTL_MS=30000" in content
    # ping is {ok, version, locked}: no lease or browser_enabled checks anywhere.
    assert "browser_enabled" not in content and "browser_enabled" not in popup
    assert "state.session_id" not in content
    assert "check.session_id" not in content
    assert "CONNECTION_PROTOCOL" not in popup
    # Legacy flag kept alongside the nonce for compatibility.
    assert "user_gesture:true" in content
    assert "gesture_nonce_invalid" in content and "gesture_nonce_invalid" in background
