#!/usr/bin/env python3
"""Generate Sources/LGKCore/Primitives/Casefold.swift from Python's str.casefold().

Stdlib only. Every code point c with chr(c).casefold() != chr(c) becomes one table row, so the Swift
side applies the table per scalar, with no normalisation. Run: python3 Scripts/make_casefold.py
"""
import pathlib
import sys
import unicodedata

rows = []
for c in range(0x110000):
    if 0xD800 <= c <= 0xDFFF:
        continue
    folded = chr(c).casefold()
    if folded != chr(c):
        rows.append((c, [ord(x) for x in folded]))

flat = []
for c, seq in rows:
    flat.extend([c, len(seq), *seq])

lines = []
for i in range(0, len(flat), 12):
    lines.append("        " + ", ".join(f"0x{v:X}" for v in flat[i:i + 12]) + ",")

out = f"""// GENERATED by Scripts/make_casefold.py. Do not edit.
// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}; {len(rows)} code points.

/// Python `str.casefold()`, applied per Unicode scalar with no normalisation (Python never composes or
/// decomposes when folding). Use it wherever the desktop compares casefolded text.
public enum Casefold {{
    public static let unicodeVersion = "{unicodedata.unidata_version}"

    public static func fold(_ s: String) -> String {{
        var out = String.UnicodeScalarView()
        for sc in s.unicodeScalars {{
            if let seq = table[sc.value] {{
                for v in seq {{ out.append(Unicode.Scalar(v)!) }}
            }} else {{
                out.append(sc)
            }}
        }}
        return String(out)
    }}

    static let table: [UInt32: [UInt32]] = {{
        var t: [UInt32: [UInt32]] = [:]
        var i = 0
        while i < flat.count {{
            let n = Int(flat[i + 1])
            t[flat[i]] = Array(flat[(i + 2)..<(i + 2 + n)])
            i += 2 + n
        }}
        return t
    }}()

    /// Rows of `code point, count, folded scalars...`.
    private static let flat: [UInt32] = [
{chr(10).join(lines)}
    ]
}}
"""
target = pathlib.Path(__file__).resolve().parent.parent / "Sources/LGKCore/Primitives/Casefold.swift"
target.write_bytes(out.encode("utf-8"))
print(f"wrote {target} ({len(rows)} rows)")
