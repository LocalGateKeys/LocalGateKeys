#!/usr/bin/env python3
"""Generate Sources/LGKCore/Strength/LookalikeTables.swift for the lookalike classifier.

The Swift standard library exposes neither the Unicode Bidi_Class nor the joining types, so the tables the
desktop takes from `unicodedata.bidirectional` and the `idna` package (CheckJoiners, the RFC 5893 Bidi rule)
are generated here. The joining-type and virama tables are the same text as the Kotlin port's
`IdnaTables.kt` (this script checks that). Run with the desktop's venv: python Scripts/make_lookalike_tables.py
"""
import pathlib
import re
import sys
import unicodedata

import idna
import idna.idnadata as idnadata

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
OUT = HERE.parent / "Sources" / "LGKCore" / "Strength" / "LookalikeTables.swift"
KOTLIN = REPO / "android" / "lgk-core" / "src" / "main" / "kotlin" / "app" / "localgatekeys" / "core" / "security" / "IdnaTables.kt"


def table(ranges):
    return " ".join(f"{a:x}" if a == b else f"{a:x}-{b:x}" for a, b in ranges)


def joining(kind):
    out = []
    for packed in idnadata.joining_types[kind]:
        start, end = packed >> 32, (packed & 0xFFFFFFFF) - 1
        out.append((start, end))
    return out


def virama():
    return [(c, c) for c in range(0x110000) if unicodedata.combining(chr(c)) == 9]


def bidi():
    """Every Bidi_Class run except L; `U` is unassigned (`bidirectional` answers '')."""
    def cls(cp):
        return unicodedata.bidirectional(chr(cp)) or "U"
    runs, start, current = [], 0, cls(0)
    for cp in range(1, 0x110000):
        c = cls(cp)
        if c != current:
            runs.append((start, cp - 1, current))
            start, current = cp, c
    runs.append((start, 0x10FFFF, current))
    return [r for r in runs if r[2] != "L"]


def kotlin_table(name):
    text = KOTLIN.read_text(encoding="utf-8")
    m = re.search(rf"const val {name} =\s*((?:\"[^\"]*\"\s*\+?\s*)+)", text)
    return "".join(re.findall(r"\"([^\"]*)\"", m.group(1))).strip()


def literal(name, text, width=110):
    words, lines, line = text.split(" "), [], ""
    for w in words:
        if line and len(line) + 1 + len(w) > width:
            lines.append(line)
            line = w
        else:
            line = f"{line} {w}" if line else w
    lines.append(line)
    body = "\n".join(f"        {ln}" for ln in lines)
    return f'    static let {name} = """\n{body}\n        """\n'


def main():
    tables = {"joiningL": table(joining("L")), "joiningD": table(joining("D")),
              "joiningR": table(joining("R")), "joiningT": table(joining("T")), "virama": table(virama())}
    for swift, kotlin in (("joiningL", "JOINING_L"), ("joiningD", "JOINING_D"), ("joiningR", "JOINING_R"),
                          ("joiningT", "JOINING_T"), ("virama", "VIRAMA")):
        if KOTLIN.exists() and kotlin_table(kotlin) != tables[swift]:
            sys.exit(f"{swift} differs from IdnaTables.kt {kotlin}")
    runs = bidi()
    bidi_text = " ".join((f"{a:x}" if a == b else f"{a:x}-{b:x}") + f":{c}" for a, b, c in runs)
    out = [
        "// GENERATED by Scripts/make_lookalike_tables.py. Do not edit.",
        f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}, idna {idna.__version__ if hasattr(idna, '__version__') else '?'}.",
        "",
        "/// Tables the lookalike parser needs and the standard library does not expose: the joining types and",
        "/// viramas of the UTS-46 CheckJoiners rule (RFC 5892 Appendix A, as `idna.valid_contextj` applies it; the",
        "/// same text as Kotlin `IdnaTables`), and the Unicode Bidi_Class for the RFC 5893 Bidi rule",
        "/// (`unicodedata.bidirectional`). Hex code points, `a-b` = inclusive range; `bidi` lists every run that is",
        "/// not `L`, as `range:class`, with `U` for an unassigned code point.",
        "enum LookalikeTables {",
        "    static let unicodeVersion = \"%s\"" % unicodedata.unidata_version,
        "",
    ]
    text = "\n".join(out) + "\n"
    for name in ("joiningL", "joiningD", "joiningR", "joiningT", "virama"):
        text += literal(name, tables[name]) + "\n"
    text += literal("bidi", bidi_text)
    text += "}\n"
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT} ({len(runs)} bidi runs)")


if __name__ == "__main__":
    main()
